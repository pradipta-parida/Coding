"""
Comparison Operators:

When we compare two numbers, we use compare type of operators.

The result or output given in boolean type (true or false).

"""

a = int(input("Enter first number: "))
b = int(input("Enter second number: "))

print(a > b)
print(a < b)
# Compare LHS value and RHS value
print(a == b)
# Not Equal to operator
print(a != b)
print(a >= b)
print(a <= b)
print(b <= b)
