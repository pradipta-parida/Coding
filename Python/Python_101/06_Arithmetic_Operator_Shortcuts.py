"""
Arithmetic Shortcuts

"""

a = int(input("Enter a number: "))

a = a + 2
print("Sum is: " + str(a))

# Shortcut for above operations
b = int(input("Enter a number: "))
b += 2
print("Sum is: " + str(b))

# Similarly, below shortcuts for other arithmetic operations
c = int(input("Enter a number: "))
c -= 2
print("Difference is: " + str(c))

d = int(input("Enter a number: "))
d *= 4
print("Product is: " + str(d))







